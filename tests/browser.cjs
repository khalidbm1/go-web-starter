const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')

async function main() {
  const base = process.env.BASE_URL || 'http://localhost:8080'
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const page = await context.newPage()
    page.setDefaultTimeout(12000)
    const crashes = []
    page.on('pageerror', error => crashes.push(error.message))
    const email = 'browser-' + randomUUID() + '@example.test'
    const password = randomUUID()
    await page.goto(base)
    await page.getByRole('heading', { name: /a clearer view of your clients/i }).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
    await page.getByRole('link', { name: 'Create an account' }).click()
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Create account' }).click()
    await page.getByRole('heading', {name:'No clients yet.'}).waitFor()
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.getByRole('button', { name: 'New client' }).click()
    await page.getByLabel('Title').fill('Cedar Studio')
    await page.getByLabel('Notes').fill('Send proposal')
    await page.getByLabel('Status').selectOption('active')
    await page.getByRole('button', { name: 'Save client' }).click()
    await page.getByRole('heading', { name: 'Cedar Studio' }).waitFor()
    await page.getByRole('button', { name: 'Edit client' }).click()
    await page.getByLabel('Title').fill('Cedar Design')
    await page.getByRole('button', { name: 'Save client' }).click()
    await page.getByRole('heading', { name: 'Cedar Design' }).waitFor()
    await page.getByRole('button', { name: 'Sign out' }).click()
    await page.getByRole('link', { name: 'Sign in', exact:true }).click()
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', {name:'Sign in'}).click()
    await page.getByRole('button', {name:'Cedar Design'}).click()
    await page.getByText('Send proposal', {exact:true}).waitFor()
    await page.getByRole('button', {name:'Delete client'}).click()
    await page.getByRole('button', {name:'Cancel'}).click()
    await page.getByRole('button', {name:'Delete client'}).click()
    await page.getByRole('button', {name:'Confirm delete'}).click()
    await page.getByRole('heading', {name:'No clients yet.'}).waitFor()
    await page.getByRole('link',{name:'Invoices',exact:true}).click()
    await page.getByRole('heading',{name:'No invoices yet.'}).waitFor()
    await page.getByRole('button',{name:'New invoice'}).click()
    await page.getByLabel('Title').fill('November invoice')
    await page.getByRole('button',{name:'Save invoice'}).click()
    await page.getByRole('heading',{name:'November invoice'}).waitFor()
    await page.getByRole('button',{name:'All invoices',exact:false}).click()
    assert.equal(await page.getByRole('definition').first().innerText(),'1')
    await page.getByRole('link',{name:'Clients',exact:true}).click()
    await page.getByRole('heading',{name:'No clients yet.'}).waitFor()
    assert.equal(await page.getByRole('definition').first().innerText(),'0')

    await page.goto(base+'/admin')
    await page.getByRole('heading',{name:'Administrator access required'}).waitFor()
    await page.getByRole('link',{name:'Profile',exact:true}).click()
    await page.getByLabel('Display name').fill('Rana Karim')
    await page.getByLabel('Bio',{exact:true}).fill('Studio coordinator')
    await page.getByRole('button',{name:'Save profile'}).click()
    await page.getByText('Your profile was saved.').waitFor()
    await page.reload()
    await page.getByLabel('Display name').waitFor()
    assert.equal(await page.getByLabel('Display name').inputValue(),'Rana Karim')
    assert.equal(await page.getByLabel('Bio',{exact:true}).inputValue(),'Studio coordinator')

    const changedEmail='updated-'+randomUUID()+'@example.test'
    const changedPassword=randomUUID()
    await page.getByLabel('Email address').fill(changedEmail)
    await page.getByLabel('Current password to change email').fill(password)
    await page.getByRole('button',{name:'Save profile'}).click()
    await page.waitForURL('**/signin?updated=1')
    async function login(address,secret){
      await page.getByLabel('Email address').fill(address)
      await page.getByLabel('Password',{exact:true}).fill(secret)
      await page.getByRole('button',{name:'Sign in',exact:true}).click()
      await page.waitForURL('**/app')
    }
    await login(changedEmail,password)
    await page.getByRole('link',{name:'Profile',exact:true}).click()
    await page.getByLabel('Current password',{exact:true}).fill(password)
    await page.getByLabel('New password',{exact:true}).fill(changedPassword)
    await page.getByRole('button',{name:'Change password',exact:true}).click()
    await page.waitForURL('**/signin?updated=1')

    if(!process.env.SAMPLE_DIR)throw Error('Set SAMPLE_DIR to the disposable generated Compose project.')
    require('node:child_process').execFileSync('docker',['compose','-f','compose.yaml','-f','compose.test.yaml','exec','-T','web','website','admin','promote',changedEmail],{cwd:process.env.SAMPLE_DIR,stdio:'pipe'})
    await login(changedEmail,changedPassword)
    await page.getByRole('link',{name:'Admin panel'}).click()
    await page.getByRole('heading',{name:'Admin dashboard'}).waitFor()
    await page.getByRole('button',{name:'Create user'}).click()
    const managed='managed-'+randomUUID()+'@example.test'
    await page.getByLabel('Email address').fill(managed)
    await page.getByLabel('Display name').fill('Managed account')
    await page.getByLabel('Initial password').fill(randomUUID())
    await page.getByRole('button',{name:'Create account'}).click()
    await page.getByText('Account created.').waitFor()
    await page.getByLabel('Find users').fill(managed)
    await page.getByRole('button',{name:'Search',exact:true}).click()
    const manage=()=>page.getByRole('button',{name:'Manage '+managed,exact:true}).click()
    await manage()
    await page.getByLabel('Account access').selectOption('disabled')
    await page.getByRole('button',{name:'Save account'}).click()
    await page.getByText('Account saved.').waitFor()
    await page.getByRole('listitem').filter({hasText:managed}).getByText('Disabled',{exact:true}).waitFor()
    await manage()
    await page.getByLabel('Account access').selectOption('active')
    await page.getByLabel('Role',{exact:true}).selectOption('admin')
    await page.getByRole('button',{name:'Save account'}).click()
    await page.getByText('Account saved.').waitFor()
    await page.getByRole('listitem').filter({hasText:managed}).getByText('Administrator',{exact:true}).waitFor()
    await manage()
    await page.getByRole('button',{name:'Delete account',exact:true}).click()
    await page.getByRole('button',{name:'Confirm delete account'}).click()
    await page.getByRole('status').filter({hasText:'Account deleted.'}).waitFor()
    await page.getByText('No users match this search.').waitFor()
    await page.getByRole('button', {name:'Sign out'}).click()
    await page.goto(base+'/app')
    await page.waitForURL('**/signin')
    assert.deepEqual(crashes, [])
    console.log('Chrome passed mobile landing, account creation, create/read/edit/delete, persistence after sign-in, delete confirmation, profile and credential changes, administrator provisioning and user lifecycle, module isolation, dashboards, and private-route redirect.')
    await context.close()
  } finally { await browser.close() }
}
main().catch(err => { console.error(err); process.exitCode=1 })
