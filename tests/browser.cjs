const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { chromium } = require(process.env.PLAYWRIGHT_CORE || 'playwright-core')

async function main() {
  const base = process.env.BASE_URL || 'http://localhost:8080'
  const browser = await chromium.launch({ channel: 'chrome', headless: true })
  try {
    const context = await browser.newContext({ viewport: { width: 390, height: 844 } })
    const page = await context.newPage()
    page.setDefaultTimeout(12000)
    const crashes = []
    page.on('pageerror', error => crashes.push(error.message))
    const email = 'browser-' + randomUUID() + '@example.test'
    const password = randomUUID()
    await page.goto(base)
    await page.getByRole('heading', { name: /a clearer view of your clients/i }).waitFor()
    assert(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth))
    await page.getByRole('link', { name: 'Create an account' }).click()
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', { name: 'Create account' }).click()
    await page.getByRole('heading', {name:'No clients yet.'}).waitFor()
    await page.setViewportSize({ width: 1280, height: 800 })
    await page.getByRole('button', { name: 'New client' }).click()
    await page.getByLabel('Title').fill('Cedar Studio')
    await page.getByLabel('Notes').fill('Send proposal')
    await page.getByLabel('Status').selectOption('active')
    await page.getByRole('button', { name: 'Save client' }).click()
    await page.getByRole('heading', { name: 'Cedar Studio' }).waitFor()
    await page.getByRole('button', { name: 'Edit client' }).click()
    await page.getByLabel('Title').fill('Cedar Design')
    await page.getByRole('button', { name: 'Save client' }).click()
    await page.getByRole('heading', { name: 'Cedar Design' }).waitFor()
    await page.getByRole('button', { name: 'Sign out' }).click()
    await page.getByRole('link', { name: 'Sign in', exact:true }).click()
    await page.getByLabel('Email address').fill(email)
    await page.getByLabel('Password', { exact: true }).fill(password)
    await page.getByRole('button', {name:'Sign in'}).click()
    await page.getByRole('button', {name:'Cedar Design'}).click()
    await page.getByText('Send proposal', {exact:true}).waitFor()
    await page.getByRole('button', {name:'Delete client'}).click()
    await page.getByRole('button', {name:'Cancel'}).click()
    await page.getByRole('button', {name:'Delete client'}).click()
    await page.getByRole('button', {name:'Confirm delete'}).click()
    await page.getByRole('heading', {name:'No clients yet.'}).waitFor()
    await page.getByRole('button', {name:'Sign out'}).click()
    await page.goto(base+'/app')
    await page.waitForURL('**/signin')
    assert.deepEqual(crashes, [])
    console.log('Chrome passed mobile landing, account creation, create/read/edit/delete, persistence after sign-in, delete confirmation, and private-route redirect.')
    await context.close()
  } finally { await browser.close() }
}
main().catch(err => { console.error(err); process.exitCode=1 })
